"""Private partition manifests, immutable generations and paged attempt evidence.

The index is separate from the worker's writable data directory. Every path is
generated by the instance; business keys and node names are SQL values only.
"""

import copy
import hashlib
import json
import sqlite3
import threading
from contextlib import contextmanager
from dataclasses import asdict

from .datasets import Dataset
from .util import Problem, clean, digest, dumps, literal, qi, uid


class PartitionStorage:
    def __init__(self, paths, worktree, environment):
        self.root = paths.home / "partitions" / digest([worktree, environment])
        self.data = self.root / "data"
        self.data.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.lock = threading.RLock()
        with self.connect() as db:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS manifests (
                    id TEXT PRIMARY KEY, signature TEXT NOT NULL, run TEXT NOT NULL,
                    metadata TEXT NOT NULL
                );
            """)
            db.executescript("""
                CREATE TABLE IF NOT EXISTS entries (
                    manifest TEXT NOT NULL, ordinal INTEGER NOT NULL, id TEXT NOT NULL,
                    key_hash TEXT NOT NULL, evidence TEXT NOT NULL,
                    PRIMARY KEY (manifest, ordinal), UNIQUE (manifest, id)
                );
                CREATE TABLE IF NOT EXISTS attempts (
                    run TEXT NOT NULL, partition_id TEXT NOT NULL, node TEXT NOT NULL,
                    state TEXT NOT NULL, PRIMARY KEY (run, partition_id, node)
                );
                CREATE TABLE IF NOT EXISTS results (
                    node TEXT NOT NULL, key_hash TEXT NOT NULL, state TEXT NOT NULL,
                    PRIMARY KEY (node, key_hash)
                );
                CREATE TABLE IF NOT EXISTS artifacts (
                    id TEXT PRIMARY KEY, node TEXT NOT NULL, key_hash TEXT NOT NULL,
                    mandatory INTEGER NOT NULL, metadata TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS manifest_signature ON manifests(signature);
            """)

    @contextmanager
    def connect(self):
        db = sqlite3.connect(self.root / "index.sqlite", timeout=30)
        db.execute("PRAGMA journal_mode=WAL")
        try:
            with db:
                yield db
        finally:
            db.close()

    def manifest(self, identity=None, signature=None):
        with self.lock, self.connect() as db:
            row = db.execute(
                "SELECT metadata FROM manifests WHERE id=?"
                if identity
                else "SELECT metadata FROM manifests WHERE signature=? ORDER BY rowid DESC LIMIT 1",
                [identity or signature],
            ).fetchone()
        return json.loads(row[0]) if row else None

    def publish_manifest(self, metadata, entries):
        with self.lock, self.connect() as db:
            db.execute(
                "INSERT INTO manifests VALUES (?,?,?,?)",
                [metadata["id"], metadata["signature"], metadata["run"], dumps(metadata)],
            )
            db.executemany(
                "INSERT INTO entries VALUES (?,?,?,?,?)",
                [(metadata["id"], e["ordinal"], e["partition_id"], e["key_hash"], dumps(e)) for e in entries],
            )

    def entries(self, manifest, offset=0, limit=None):
        with self.lock, self.connect() as db:
            rows = db.execute(
                "SELECT evidence FROM entries WHERE manifest=? AND ordinal>=? ORDER BY ordinal LIMIT ?",
                [manifest, offset, limit if limit is not None else -1],
            ).fetchall()
        return [json.loads(r[0]) for r in rows]

    def entry(self, manifest, partition_id):
        with self.lock, self.connect() as db:
            row = db.execute(
                "SELECT evidence FROM entries WHERE manifest=? AND id=?", [manifest, partition_id]
            ).fetchone()
        if row is None:
            raise Problem("Partition does not belong to this manifest", 404)
        return json.loads(row[0])

    def attempt(self, run, partition_id, node, state):
        with self.lock, self.connect() as db:
            db.execute(
                "INSERT OR REPLACE INTO attempts VALUES (?,?,?,?)",
                [run, partition_id, node, dumps(clean(state))],
            )

    def attempts(self, run, partition_id):
        with self.lock, self.connect() as db:
            rows = db.execute(
                "SELECT node,state FROM attempts WHERE run=? AND partition_id=?", [run, partition_id]
            ).fetchall()
        return {node: json.loads(state) for node, state in rows}

    def result(self, node, key_hash):
        with self.lock, self.connect() as db:
            row = db.execute(
                "SELECT state FROM results WHERE node=? AND key_hash=?", [node, key_hash]
            ).fetchone()
        return json.loads(row[0]) if row else {}

    def record(self, node, entry, state, outputs=None):
        previous = self.result(node, entry["key_hash"])
        record = {**previous, "attempt": copy.deepcopy(state)}
        if state["status"] == "success":
            record["success"] = {**copy.deepcopy(state), "artifacts": outputs or {}}
        with self.lock, self.connect() as db:
            db.execute(
                "INSERT OR REPLACE INTO results VALUES (?,?,?)",
                [node, entry["key_hash"], dumps(clean(record))],
            )

    @staticmethod
    def checksum(path):
        with path.open("rb") as stream:
            return hashlib.file_digest(stream, "sha256").hexdigest()

    def save(self, cursor, dataset, entry, mandatory, budget, retention_run=None):
        identity = uid("partdata_")
        path = self.data / (identity + ".parquet")
        temporary = self.data / (identity + ".partial")
        ordinal = uid("__dp_order_")
        finished, exceeded = threading.Event(), threading.Event()

        def bound_write():
            while not finished.wait(0.01):
                try:
                    if temporary.stat().st_size > budget:
                        exceeded.set()
                        cursor.interrupt()
                        return
                except FileNotFoundError:
                    pass

        monitor = (
            threading.Thread(target=bound_write, name="partition-preview-cap") if not mandatory else None
        )
        if monitor:
            monitor.start()
        try:
            cursor.execute(
                f"COPY (SELECT rowid AS {qi(ordinal)}, * FROM {qi(dataset.storage)} ORDER BY rowid) TO {literal(str(temporary))} (FORMAT PARQUET)"
            )
            size = temporary.stat().st_size
            if not mandatory and size > budget:
                return None
            checksum = self.checksum(temporary)
            temporary.replace(path)
            metadata = {
                "id": identity,
                "dataset": clean(asdict(dataset)),
                "ordinal_column": ordinal,
                "bytes": size,
                "checksum": checksum,
                "partition": copy.deepcopy(entry),
                "retention_run": retention_run or dataset.created,
            }
            with self.lock, self.connect() as db:
                db.execute(
                    "INSERT INTO artifacts VALUES (?,?,?,?,?)",
                    [identity, dataset.node, entry["key_hash"], int(mandatory), dumps(metadata)],
                )
            return metadata
        except Exception:
            path.unlink(missing_ok=True)
            if exceeded.is_set():
                return None
            raise
        finally:
            finished.set()
            if monitor:
                monitor.join()
            temporary.unlink(missing_ok=True)

    def artifact(self, identity):
        if not identity:
            return None
        with self.lock, self.connect() as db:
            row = db.execute("SELECT metadata FROM artifacts WHERE id=?", [identity]).fetchone()
        return json.loads(row[0]) if row else None

    def available(self, metadata):
        if (
            not metadata
            or not isinstance(metadata.get("id"), str)
            or not metadata["id"].startswith("partdata_")
            or not metadata["id"].replace("_", "").isalnum()
        ):
            return False
        path = self.data / (metadata["id"] + ".parquet")
        try:
            return (
                path.is_file()
                and path.stat().st_size == metadata["bytes"]
                and self.checksum(path) == metadata["checksum"]
            )
        except OSError:
            return False

    def restore(self, cursor, metadata):
        if not self.available(metadata):
            raise Problem("partition_not_retained: partition data is missing or its checksum changed", 409)
        data = Dataset(**copy.deepcopy(metadata["dataset"]))
        data.disk = True
        data.artifact_id = metadata["id"]
        data.partition = copy.deepcopy(metadata["partition"])
        data.id = uid("data_")
        data.storage = data.id + "_storage"
        marker = qi(metadata["ordinal_column"])
        path = literal(str(self.data / (metadata["id"] + ".parquet")))
        cursor.execute(
            f"CREATE VIEW {qi(data.storage)} AS SELECT * EXCLUDE ({marker}), {marker} AS rowid FROM read_parquet({path})"
        )
        projection = ", ".join(f"{qi(data.stored(c['name']))} AS {qi(c['name'])}" for c in data.columns)
        cursor.execute(f"CREATE VIEW {qi(data.table)} AS SELECT {projection} FROM {qi(data.storage)}")
        return data

    def collect(self, cursor, node, port, artifacts, columns=None):
        """UNION ALL preserves branch order; each branch restores its private row order."""
        inputs = [self.restore(cursor, a) for a in artifacts]
        columns = inputs[0].columns if inputs else columns
        if columns is None:
            raise Problem("partition_schema_unavailable: no typed output is available")
        if any(data.columns != columns for data in inputs):
            raise Problem("partition_schema: output columns or types differ between keys")
        identity = uid("data_")
        mapping = {c["name"]: uid("__dp_user_") for c in columns if c["name"].casefold() == "rowid"}
        statements, origins, offset = [], [], 0
        for data in inputs:
            projection = ", ".join(
                f"{qi(data.stored(c['name']))} AS {qi(mapping.get(c['name'], c['name']))}" for c in columns
            )
            statements.append(f"(SELECT {projection}, rowid + {offset} AS rowid FROM {qi(data.storage)})")
            origins.append(
                {
                    "start": offset,
                    "count": data.count,
                    "partition": data.partition,
                    "run": data.run,
                    "dataset": data.id,
                }
            )
            offset += data.count
        query = (
            " UNION ALL ".join(statements)
            if statements
            else "SELECT "
            + ", ".join(
                f"CAST(NULL AS {c['type']}) AS {qi(mapping.get(c['name'], c['name']))}" for c in columns
            )
            + ", 0::BIGINT AS rowid WHERE FALSE"
        )
        data = Dataset(
            id=identity,
            node=node,
            port=port,
            columns=columns,
            count=offset,
            run=inputs[0].run if inputs else "",
            query=query,
            bindings={},
            dependencies={d.table: d.id for d in inputs},
            fingerprint=digest([a["dataset"]["fingerprint"] for a in artifacts]),
            storage=identity + "_storage",
            column_map=mapping,
            disk=True,
            origins=origins,
        )
        cursor.execute(f"CREATE VIEW {qi(data.storage)} AS {query}")
        projection = ", ".join(f"{qi(data.stored(c['name']))} AS {qi(c['name'])}" for c in columns)
        cursor.execute(f"CREATE VIEW {qi(data.table)} AS SELECT {projection} FROM {qi(data.storage)}")
        return data, inputs

    def trim_optional(self, preview, pinned):
        """Retain the most recent successful output keys within one global byte cap."""
        with self.lock, self.connect() as db:
            rows = [
                json.loads(row[0]) for row in db.execute("SELECT metadata FROM artifacts WHERE mandatory=0")
            ]
            rows.sort(
                key=lambda a: (a["retention_run"], a["partition"]["ordinal"], a["dataset"]["created"]),
                reverse=True,
            )
            used = sum(a["bytes"] for a in rows if a["id"] in pinned)
            counts, seen = {}, set()
            for artifact in rows:
                output = (artifact["dataset"]["node"], artifact["dataset"]["port"])
                key = (*output, artifact["partition"]["key_hash"])
                keep = key not in seen and (
                    preview["keep"] == "all" or counts.get(output, 0) < preview.get("count", 1)
                )
                seen.add(key)
                if artifact["id"] in pinned:
                    counts[output] = counts.get(output, 0) + 1
                    continue
                if keep and used + artifact["bytes"] <= preview["max_bytes"]:
                    used += artifact["bytes"]
                    counts[output] = counts.get(output, 0) + 1
                else:
                    (self.data / (artifact["id"] + ".parquet")).unlink(missing_ok=True)
                    db.execute("DELETE FROM artifacts WHERE id=?", [artifact["id"]])

    def prune(self, entries, preview, pinned):
        """Evict optional generations by run/ordinal; mandatory live inputs are never budgeted."""
        current = {entry["key_hash"] for entry in entries}
        with self.lock, self.connect() as db:
            # Results are indexed independently of a manifest, allowing selective launches.
            successes = [
                json.loads(state).get("success", {})
                for key_hash, state in db.execute("SELECT key_hash,state FROM results")
                if key_hash in current
            ]
            live = {a["id"] for state in successes for a in state.get("artifacts", {}).values()}
            records = [
                (identity, mandatory, json.loads(metadata))
                for identity, mandatory, metadata in db.execute("SELECT id,mandatory,metadata FROM artifacts")
            ]
            keep = set(pinned) | {
                identity for identity, mandatory, _ in records if mandatory and identity in live
            }
            optional = sorted(
                [
                    (identity, meta)
                    for identity, mandatory, meta in records
                    if not mandatory and identity in live
                ],
                key=lambda item: (item[1]["retention_run"], item[1]["partition"]["ordinal"]),
                reverse=True,
            )
            used, counts = 0, {}
            for identity, meta in optional:
                output = (meta["dataset"]["node"], meta["dataset"]["port"])
                if (
                    preview["keep"] == "none"
                    or (preview["keep"] == "last" and counts.get(output, 0) >= preview["count"])
                    or used + meta["bytes"] > preview["max_bytes"]
                ):
                    continue
                keep.add(identity)
                used += meta["bytes"]
                counts[output] = counts.get(output, 0) + 1
            for identity, _, _ in records:
                if identity not in keep:
                    (self.data / (identity + ".parquet")).unlink(missing_ok=True)
                    db.execute("DELETE FROM artifacts WHERE id=?", [identity])
